"""Models for LLM proposals and proposed punch corrections."""

from datetime import datetime
from typing import Any

from pydantic import BaseModel, Field, field_validator

from .exception import PunchType


class ProposedPunch(BaseModel):
    """An individual punch suggested in a proposal."""

    punch_type: PunchType
    timestamp: datetime
    action: str = "insert"  # "insert", "modify", "remove", "keep"
    notes: str | None = None

    @field_validator("punch_type", mode="before")
    @classmethod
    def normalize_punch_type(cls, v: Any) -> PunchType:
        if isinstance(v, PunchType):
            return v
        if isinstance(v, str):
            clean = v.strip().upper()
            if clean in ("CLOCK_IN", "IN"):
                return PunchType.IN
            if clean in ("CLOCK_OUT", "OUT"):
                return PunchType.OUT
            if clean in ("BREAK_START", "MEAL_START", "MEAL_OUT"):
                return PunchType.BREAK_START
            if clean in ("BREAK_END", "MEAL_END", "MEAL_IN"):
                return PunchType.BREAK_END
            try:
                return PunchType(clean)
            except ValueError:
                pass
        raise ValueError(f"Unsupported punch_type: {v}")


class LLMProposal(BaseModel):
    """Structured proposal generated by Person 4's LLM module.

    Required fields:
    - exception_id
    - suggested_action
    - proposed_punches
    - policy_citations
    - reasoning
    """

    proposal_id: str | None = None
    exception_id: str
    suggested_action: str
    proposed_punches: list[ProposedPunch] = Field(default_factory=list)
    policy_citations: list[str] = Field(default_factory=list)
    reasoning: str
    raw_llm_hours: float | None = None  # Never trusted; overridden by validator
