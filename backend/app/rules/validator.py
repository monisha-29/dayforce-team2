"""LLM Proposal Validator for Timecard Exception Agent.

Independently verifies every proposed correction generated by Person 4's LLM module.
The validator executes five deterministic checks:
1. JSON Format and Schema Integrity
2. Policy Clause Existence and Relevance
3. Working Hours Recalculation (Python performs all math; LLM calculations are never trusted)
4. New Violations Check (Ensures fix introduces zero new timecard exceptions)
5. Allowed Limits and Safety Sanity (Timestamp sanity, shift duration caps, prompt injection defense)

Principle: The LLM suggests. Code decides. A human approves.
The validator NEVER directly modifies employee timecards.
"""

import json
import re
from collections.abc import Sequence
from datetime import datetime, timedelta
from typing import Any

from pydantic import ValidationError

from .detectors import RulesConfig, detect_shift_exceptions
from .hours_calculator import HoursCalculator
from .models.exception import (
    ExceptionType,
    Punch,
    Schedule,
    TimecardException,
)
from .models.proposal import LLMProposal, ProposedPunch
from .models.validation import (
    ValidationCheckDetail,
    ValidationErrorItem,
    ValidationResult,
)
from .policy_loader import policy_registry

# Patterns indicating prompt injection attacks in LLM reasoning or notes
INJECTION_PATTERNS = [
    re.compile(r"ignore\s+(all\s+)?(previous\s+)?instructions", re.IGNORECASE),
    re.compile(r"override\s+(all\s+)?policy", re.IGNORECASE),
    re.compile(r"bypass\s+validation", re.IGNORECASE),
    re.compile(r"system\s+prompt", re.IGNORECASE),
    re.compile(r"grant\s+(24|99)\s+hours", re.IGNORECASE),
    re.compile(r"admin\s+mode", re.IGNORECASE),
]


def _violation_summary(violations: list[TimecardException], shown: int = 3) -> str:
    """One-line summary naming the violations, so managers and the retry prompt see what failed."""
    names = "; ".join(v.description for v in violations[:shown])
    extra = f"; +{len(violations) - shown} more" if len(violations) > shown else ""
    return f"Proposed timecard triggered {len(violations)} violation(s): {names}{extra}"


class ProposalValidator:
    """Deterministic safety validator for LLM-generated timecard proposals."""

    def __init__(self, config: RulesConfig | None = None) -> None:
        self.config = config or RulesConfig()
        self.calculator = HoursCalculator(self.config.calculator)

    def validate(
        self,
        original_punches: Sequence[Punch],
        proposal_input: str | dict[str, Any] | LLMProposal,
        original_schedule: Schedule | None = None,
        original_exception: TimecardException | None = None,
    ) -> ValidationResult:
        """Run all 5 safety checks on a proposed correction."""
        errors: list[ValidationErrorItem] = []
        warnings: list[str] = []
        check_details: list[ValidationCheckDetail] = []
        checks_map: dict[str, bool] = {
            "format_valid": False,
            "policy_clauses_valid": False,
            "working_hours_valid": False,
            "no_new_violations": False,
            "limits_valid": False,
        }

        # -------------------------------------------------------------
        # CHECK 1: JSON FORMAT & SCHEMA
        # -------------------------------------------------------------
        proposal: LLMProposal | None = None
        raw_dict: dict[str, Any] | None = None

        if isinstance(proposal_input, str):
            try:
                parsed = json.loads(proposal_input)
                if not isinstance(parsed, dict):
                    err_msg = f"Proposal JSON must be an object/dict, got {type(parsed).__name__}"
                    errors.append(
                        ValidationErrorItem(code="INVALID_PROPOSAL_TYPE", message=err_msg)
                    )
                    check_details.append(
                        ValidationCheckDetail(
                            check_name="format_valid", passed=False, message=err_msg
                        )
                    )
                    return self._build_result(
                        False, errors, warnings, checks_map, check_details, None, [], err_msg
                    )
                raw_dict = parsed
            except json.JSONDecodeError as jde:
                err_msg = f"Proposal is not valid JSON: {jde!s}"
                errors.append(ValidationErrorItem(code="INVALID_JSON_FORMAT", message=err_msg))
                check_details.append(
                    ValidationCheckDetail(check_name="format_valid", passed=False, message=err_msg)
                )
                return self._build_result(
                    False,
                    errors,
                    warnings,
                    checks_map,
                    check_details,
                    None,
                    [],
                    "JSON parsing failed.",
                )
        elif isinstance(proposal_input, dict):
            raw_dict = proposal_input
        elif isinstance(proposal_input, LLMProposal):
            proposal = proposal_input
        else:
            err_msg = f"Unsupported proposal payload type: {type(proposal_input).__name__}"
            errors.append(ValidationErrorItem(code="UNSUPPORTED_PAYLOAD_TYPE", message=err_msg))
            check_details.append(
                ValidationCheckDetail(check_name="format_valid", passed=False, message=err_msg)
            )
            return self._build_result(
                False, errors, warnings, checks_map, check_details, None, [], err_msg
            )

        if proposal is None and raw_dict is not None:
            # Validate required schema fields
            required_fields = [
                "exception_id",
                "suggested_action",
                "proposed_punches",
                "policy_citations",
                "reasoning",
            ]
            missing_fields = [f for f in required_fields if f not in raw_dict]
            if missing_fields:
                err_msg = f"Proposal is missing required fields: {', '.join(missing_fields)}"
                errors.append(ValidationErrorItem(code="MISSING_REQUIRED_FIELDS", message=err_msg))
                check_details.append(
                    ValidationCheckDetail(check_name="format_valid", passed=False, message=err_msg)
                )
                return self._build_result(
                    False, errors, warnings, checks_map, check_details, None, [], err_msg
                )

            try:
                proposal = LLMProposal(**raw_dict)
            except (ValidationError, ValueError, TypeError) as pe:
                err_msg = f"Proposal schema validation failed: {pe!s}"
                errors.append(ValidationErrorItem(code="SCHEMA_VALIDATION_ERROR", message=err_msg))
                check_details.append(
                    ValidationCheckDetail(check_name="format_valid", passed=False, message=err_msg)
                )
                return self._build_result(
                    False, errors, warnings, checks_map, check_details, None, [], err_msg
                )

        if proposal is None:
            err_msg = "Could not construct valid proposal from input."
            errors.append(ValidationErrorItem(code="INVALID_PROPOSAL", message=err_msg))
            check_details.append(
                ValidationCheckDetail(check_name="format_valid", passed=False, message=err_msg)
            )
            return self._build_result(
                False, errors, warnings, checks_map, check_details, None, [], err_msg
            )

        checks_map["format_valid"] = True
        check_details.append(
            ValidationCheckDetail(
                check_name="format_valid", passed=True, message="Proposal JSON schema is valid."
            )
        )

        # -------------------------------------------------------------
        # CHECK 2: POLICY CLAUSES
        # -------------------------------------------------------------
        cited_ids = [
            c.strip() for c in proposal.policy_citations if isinstance(c, str) and c.strip()
        ]
        if not cited_ids:
            err_msg = "Proposal cites no policy clauses. Every proposal must cite at least one valid company policy clause."
            errors.append(
                ValidationErrorItem(
                    code="NO_POLICY_CITED", message=err_msg, field="policy_citations"
                )
            )
        else:
            fabricated_ids = [
                cid for cid in cited_ids if not policy_registry.is_valid_clause_id(cid)
            ]
            if fabricated_ids:
                err_msg = f"Fabricated or unknown policy clause IDs cited: {', '.join(fabricated_ids)}. Only existing repository policies may be cited."
                errors.append(
                    ValidationErrorItem(
                        code="FABRICATED_POLICY_ID", message=err_msg, field="policy_citations"
                    )
                )
            else:
                # Check relevance to original exception
                if original_exception is not None:
                    exc_type = original_exception.exception_type.value
                    relevant_clauses = policy_registry.get_clauses_for_exception(exc_type)
                    relevant_ids = {rc.id for rc in relevant_clauses}
                    if not any(cid in relevant_ids for cid in cited_ids):
                        warnings.append(
                            f"None of the cited clauses ({', '.join(cited_ids)}) directly match exception type '{exc_type}'."
                        )

        if not any(e.code in ("NO_POLICY_CITED", "FABRICATED_POLICY_ID") for e in errors):
            checks_map["policy_clauses_valid"] = True
            check_details.append(
                ValidationCheckDetail(
                    check_name="policy_clauses_valid",
                    passed=True,
                    message=f"All {len(cited_ids)} cited policy clauses exist in repository catalog.",
                    details={"cited_clauses": cited_ids},
                )
            )
        else:
            check_details.append(
                ValidationCheckDetail(
                    check_name="policy_clauses_valid",
                    passed=False,
                    message="Policy clause validation failed.",
                )
            )

        # -------------------------------------------------------------
        # CHECK 3: WORKING HOURS RECALCULATION
        # -------------------------------------------------------------
        # Materialize the proposed revised timecard:
        # Original employee ID
        emp_id = (
            original_punches[0].employee_id
            if original_punches
            else (
                original_schedule.employee_id
                if original_schedule
                else (original_exception.employee_id if original_exception else "UNKNOWN")
            )
        )
        date_str = (
            original_schedule.date
            if original_schedule
            else (
                original_punches[0].timestamp.date().isoformat()
                if original_punches
                else (
                    original_exception.date
                    if original_exception
                    else datetime.now().date().isoformat()
                )
            )
        )

        proposed_timecard = self._construct_proposed_timecard(
            original_punches=original_punches,
            proposed_punches=proposal.proposed_punches,
            default_emp_id=emp_id,
        )

        daily_calc = self.calculator.calculate_daily_hours(proposed_timecard, target_date=date_str)
        validated_hours = daily_calc.net_hours

        # Check for calculation errors from the hours calculator
        if daily_calc.errors:
            for calc_err in daily_calc.errors:
                errors.append(
                    ValidationErrorItem(
                        code="CALCULATION_ERROR", message=calc_err, field="proposed_punches"
                    )
                )
        elif daily_calc.has_overlapping_punches:
            errors.append(
                ValidationErrorItem(
                    code="OVERLAPPING_PUNCHES",
                    message="Proposed punches create overlapping shift intervals.",
                    field="proposed_punches",
                )
            )

        # Verify daily overtime restrictions
        daily_limit = self.config.calculator.daily_regular_hours_limit
        is_overtime_approval = (
            "overtime" in proposal.suggested_action.lower() or "OT-01" in cited_ids
        )

        # A proposal that changes no punches cannot "create" hours: any overtime in the recorded
        # timecard already exists and is reported by its own exception.
        if (
            daily_calc.net_hours > daily_limit
            and not is_overtime_approval
            and proposal.proposed_punches
        ):
            errors.append(
                ValidationErrorItem(
                    code="OVERTIME_LIMIT_EXCEEDED",
                    message=f"Proposed shift creates {daily_calc.net_hours:.2f} working hours. Configured daily limit is {daily_limit:.1f} hours.",
                    field="proposed_punches",
                )
            )

        if not any(
            e.code in ("CALCULATION_ERROR", "OVERLAPPING_PUNCHES", "OVERTIME_LIMIT_EXCEEDED")
            for e in errors
        ):
            checks_map["working_hours_valid"] = True
            check_details.append(
                ValidationCheckDetail(
                    check_name="working_hours_valid",
                    passed=True,
                    message=f"Working hours successfully recalculated by code: {validated_hours:.2f}h.",
                    details={
                        "net_hours": validated_hours,
                        "regular_hours": daily_calc.regular_hours,
                        "daily_ot": daily_calc.daily_overtime_hours,
                    },
                )
            )
        else:
            check_details.append(
                ValidationCheckDetail(
                    check_name="working_hours_valid",
                    passed=False,
                    message="Working hours calculation failed safety checks.",
                )
            )

        # -------------------------------------------------------------
        # CHECK 4: NEW VIOLATIONS CHECK
        # -------------------------------------------------------------
        # Re-run all detectors on the proposed timecard
        new_exceptions = detect_shift_exceptions(
            employee_id=emp_id,
            date_str=date_str,
            punches=proposed_timecard,
            schedule=original_schedule,
            config=self.config,
        )

        # Violations the recorded timecard already had are not introduced by this proposal;
        # each of them is reported (and resolved) as its own exception.
        existing_ids = {
            e.exception_id
            for e in detect_shift_exceptions(
                employee_id=emp_id,
                date_str=date_str,
                punches=list(original_punches),
                schedule=original_schedule,
                config=self.config,
            )
        }

        # Check if the proposed timecard creates violations that were NOT the original exception being resolved
        introduced_violations: list[TimecardException] = []
        original_exc_type = original_exception.exception_type if original_exception else None

        for n_exc in new_exceptions:
            # If it's a completely different exception type, it's a new violation unless the
            # recorded timecard already had it
            if original_exc_type is None or n_exc.exception_type != original_exc_type:
                if n_exc.exception_id in existing_ids:
                    continue
                introduced_violations.append(n_exc)
            else:
                # Same exception type:
                # If the proposal is specifically acknowledging or approving this exception (e.g. approving overtime),
                # it is expected to remain and is not considered a new or unresolved violation.
                if is_overtime_approval and n_exc.exception_type == ExceptionType.OVERTIME:
                    continue
                if "acknowledge" in proposal.suggested_action.lower():
                    continue
                introduced_violations.append(n_exc)

        if introduced_violations:
            for iv in introduced_violations:
                errors.append(
                    ValidationErrorItem(
                        code=f"NEW_VIOLATION_{iv.exception_type.value.upper()}",
                        message=f"Proposed correction introduces or leaves unresolved violation: {iv.description}",
                        field="proposed_punches",
                    )
                )
            check_details.append(
                ValidationCheckDetail(
                    check_name="no_new_violations",
                    passed=False,
                    message=_violation_summary(introduced_violations),
                    details={"violations": [v.description for v in introduced_violations]},
                )
            )
        else:
            checks_map["no_new_violations"] = True
            check_details.append(
                ValidationCheckDetail(
                    check_name="no_new_violations",
                    passed=True,
                    message="No new violations introduced on proposed timecard.",
                )
            )

        # -------------------------------------------------------------
        # CHECK 5: ALLOWED LIMITS & SECURITY SANITY
        # -------------------------------------------------------------
        # 5a. Prompt injection detection in reasoning
        for pattern in INJECTION_PATTERNS:
            if pattern.search(proposal.reasoning):
                errors.append(
                    ValidationErrorItem(
                        code="UNAUTHORIZED_PROPOSAL_TAMPERING",
                        message="Proposal rejected: reasoning contains prompt injection or unauthorized directive patterns.",
                        field="reasoning",
                    )
                )
                break

        # 5b. Check maximum single shift duration
        max_shift = self.config.calculator.max_shift_hours
        if daily_calc.gross_hours > max_shift:
            errors.append(
                ValidationErrorItem(
                    code="EXCESSIVE_SHIFT_DURATION",
                    message=f"Gross shift duration {daily_calc.gross_hours:.2f}h exceeds maximum allowed limit of {max_shift:.1f}h.",
                    field="proposed_punches",
                )
            )

        # 5c. Check timestamp sanity (future dates)
        now = datetime.now()
        for p in proposal.proposed_punches:
            # If timestamp is more than 24 hours into the future, reject
            if p.timestamp > (now + timedelta(days=1)):
                errors.append(
                    ValidationErrorItem(
                        code="FUTURE_TIMESTAMP_PROHIBITED",
                        message=f"Proposed punch timestamp {p.timestamp.isoformat()} is in the future.",
                        field="proposed_punches",
                    )
                )

        # 5d. Check timestamp and shift date alignment
        if original_schedule or original_exception:
            ref_date_str = (
                original_schedule.date if original_schedule else original_exception.date  # type: ignore[union-attr]
            )
            try:
                ref_date = datetime.fromisoformat(ref_date_str).date()
                for p in proposal.proposed_punches:
                    p_date = p.timestamp.date()
                    if abs((p_date - ref_date).days) > 1:
                        errors.append(
                            ValidationErrorItem(
                                code="TIMESTAMP_DATE_MISMATCH",
                                message=(
                                    f"Proposed punch timestamp {p.timestamp.isoformat()} "
                                    f"deviates from target shift date {ref_date_str}."
                                ),
                                field="proposed_punches",
                            )
                        )
            except (ValueError, TypeError):
                pass

        # 5e. Check employee ownership consistency
        target_emp_id = (
            original_exception.employee_id
            if original_exception
            else (
                original_schedule.employee_id
                if original_schedule
                else (original_punches[0].employee_id if original_punches else None)
            )
        )
        if target_emp_id:
            for p in proposal.proposed_punches:
                if p.employee_id and p.employee_id.strip() != target_emp_id.strip():
                    errors.append(
                        ValidationErrorItem(
                            code="EMPLOYEE_OWNERSHIP_MISMATCH",
                            message=(
                                f"Proposed punch employee_id '{p.employee_id}' "
                                f"does not match target employee '{target_emp_id}'."
                            ),
                            field="proposed_punches",
                        )
                    )

        limit_error_codes = {
            "UNAUTHORIZED_PROPOSAL_TAMPERING",
            "EXCESSIVE_SHIFT_DURATION",
            "FUTURE_TIMESTAMP_PROHIBITED",
            "TIMESTAMP_DATE_MISMATCH",
            "EMPLOYEE_OWNERSHIP_MISMATCH",
        }
        if not any(e.code in limit_error_codes for e in errors):
            checks_map["limits_valid"] = True
            check_details.append(
                ValidationCheckDetail(
                    check_name="limits_valid",
                    passed=True,
                    message="All proposed parameters and timestamps are within allowed limits.",
                )
            )
        else:
            check_details.append(
                ValidationCheckDetail(
                    check_name="limits_valid",
                    passed=False,
                    message="Proposal violated safety limits or sanity boundaries.",
                )
            )

        # -------------------------------------------------------------
        # FINAL STATUS & COMPILATION
        # -------------------------------------------------------------
        is_valid = len(errors) == 0 and all(checks_map.values())

        if is_valid:
            explanation = (
                f"Proposal PASSED all 5 validation checks. "
                f"Recalculated net working hours: {validated_hours:.2f}h. "
                f"Cited policies: {', '.join(cited_ids)}. Ready for manager review."
            )
        else:
            explanation = (
                f"Proposal FAILED validation ({len(errors)} error(s)). "
                f"Primary failure: {errors[0].message}"
            )

        return self._build_result(
            valid=is_valid,
            errors=errors,
            warnings=warnings,
            checks_map=checks_map,
            check_details=check_details,
            validated_hours=validated_hours,
            cited_ids=cited_ids,
            explanation=explanation,
        )

    def _construct_proposed_timecard(
        self,
        original_punches: Sequence[Punch],
        proposed_punches: Sequence[ProposedPunch],
        default_emp_id: str,
    ) -> list[Punch]:
        """Merge original punches with proposed adjustments."""
        timecard = list(original_punches)

        for prop in proposed_punches:
            action = prop.action.lower()
            if action in ("insert", "add"):
                timecard.append(
                    Punch(
                        employee_id=default_emp_id,
                        timestamp=prop.timestamp,
                        punch_type=prop.punch_type,
                        source="llm_proposal",
                        notes=prop.notes,
                    )
                )
            elif action in ("modify", "replace"):
                # Replace the nearest matching punch of the same type, or append if none
                match_idx = None
                for idx, p in enumerate(timecard):
                    if p.punch_type == prop.punch_type:
                        match_idx = idx
                        break
                if match_idx is not None:
                    timecard[match_idx] = Punch(
                        employee_id=default_emp_id,
                        timestamp=prop.timestamp,
                        punch_type=prop.punch_type,
                        source="llm_proposal_edit",
                        notes=prop.notes,
                    )
                else:
                    timecard.append(
                        Punch(
                            employee_id=default_emp_id,
                            timestamp=prop.timestamp,
                            punch_type=prop.punch_type,
                            source="llm_proposal",
                            notes=prop.notes,
                        )
                    )

        return sorted(timecard, key=lambda p: p.timestamp)

    def _build_result(
        self,
        valid: bool,
        errors: list[ValidationErrorItem],
        warnings: list[str],
        checks_map: dict[str, bool],
        check_details: list[ValidationCheckDetail],
        validated_hours: float | None,
        cited_ids: list[str],
        explanation: str,
    ) -> ValidationResult:
        return ValidationResult(
            valid=valid,
            status="PASSED" if valid else "FAILED",
            errors=errors,
            warnings=warnings,
            validation_checks=checks_map,
            check_details=check_details,
            validated_working_hours=validated_hours,
            cited_policy_ids=cited_ids,
            explanation=explanation,
        )
